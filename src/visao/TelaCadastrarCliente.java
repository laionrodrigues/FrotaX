    private void jToggleButton_CadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton_CadastrarActionPerformed
        try {
            String nome = jTextField_Nome.getText();
            String sobrenome = jTextField_Sobrenome.getText();
            String dataTexto = jTextField_DataNascimento.getText();
            String cpf = jTextField_CPF.getText();
            String cnh = jTextField_CNH.getText();
            
            DateTimeFormatter formatoBR = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate dataNascimento = LocalDate.parse(dataTexto, formatoBR);
            
            Cliente cliente = new Cliente(nome, sobrenome, dataNascimento, cpf, cnh);
            gerenciadorCliente.adicionarCliente(cliente);
            javax.swing.JOptionPane.showMessageDialog(this, "Cliente cadastrado com sucesso!");
            telaCliente.carregarTabela();
            this.dispose();
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Data inválida. Use o formato dd/MM/aaaa (ex: 15/05/1995).", "Atenção", JOptionPane.WARNING_MESSAGE);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Atenção", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }      
    }//GEN-LAST:event_jToggleButton_CadastrarActionPerformed

